export type Locale = "en" | "th" | "zh";
export const locales: Locale[] = ["en", "th", "zh"];
export const defaultLocale: Locale = "en";
export const isLocale = (s: string): s is Locale => (locales as string[]).includes(s);

/** A value in every language. TypeScript refuses one with a language missing. */
export type L10n<T = string> = Record<Locale, T>;

/** The one lookup, so no component has to branch on the language itself. */
export const pick = <T,>(value: L10n<T>, locale: Locale): T => value[locale];

/** How each language is named, and how it is declared to browsers, search
    engines and link previews. `short` is what the compact header shows.
    `clock` and `range` are how it writes a time and a span of time (12.30 –
    21.00 in English and Thai, 12:30–21:00 in Chinese, where 12.30 reads as a
    date); `list` is what separates the items of a list (、 in Chinese). */
export const localeInfo: L10n<{ html: string; og: string; name: string; short: string; clock: string; range: string; list: string }> = {
  en: { html: "en", og: "en_US", name: "English", short: "EN", clock: ".", range: " – ", list: ", " },
  th: { html: "th", og: "th_TH", name: "ไทย", short: "ไทย", clock: ".", range: " – ", list: ", " },
  zh: { html: "zh-CN", og: "zh_CN", name: "简体中文", short: "中文", clock: ":", range: "–", list: "、" },
};

/** A time or a span of times, as the restaurant writes it ("12.30 – 21.00"),
    in the way this language writes it. Only the punctuation changes. */
export const clock = (text: string, locale: Locale): string =>
  text
    .replace(/\b(\d{1,2})\.(\d{2})\b/g, `$1${localeInfo[locale].clock}$2`)
    .replace(/(\d)\s*–\s*(\d)/g, `$1${localeInfo[locale].range}$2`);

